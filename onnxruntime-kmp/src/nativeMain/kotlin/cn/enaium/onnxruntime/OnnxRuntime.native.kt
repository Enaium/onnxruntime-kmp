internal class NativeSession internal constructor(
    private val ptr: CPointer<OrtSession>?,
) : Session {

    private var closed = false

    override val inputNames: List<String> by lazy { sessionNames(::inputCount, ::inputName) }
    override val outputNames: List<String> by lazy { sessionNames(::outputCount, ::outputName) }

    private fun inputCount(): ULong = memScoped {
        val out = alloc<ULongVar>()
        Ort.api.SessionGetInputCount!!(ptr, out.ptr).check()
        out.value
    }

    private fun outputCount(): ULong = memScoped {
        val out = alloc<ULongVar>()
        Ort.api.SessionGetOutputCount!!(ptr, out.ptr).check()
        out.value
    }

    private fun inputName(index: ULong): String = memScoped {
        val out = alloc<CPointerVar<ByteVar>>()
        Ort.api.SessionGetInputName!!(ptr, index, Ort.defaultAllocator, out.ptr).check()
        val name = out.value!!.toKString()
        Ort.defaultAllocator?.let { it.pointed.Free!!(it, out.value) }
        name
    }

    private fun outputName(index: ULong): String = memScoped {
        val out = alloc<CPointerVar<ByteVar>>()
        Ort.api.SessionGetOutputName!!(ptr, index, Ort.defaultAllocator, out.ptr).check()
        val name = out.value!!.toKString()
        Ort.defaultAllocator?.let { it.pointed.Free!!(it, out.value) }
        name
    }

    private inline fun sessionNames(
        count: () -> ULong,
        nameOf: (ULong) -> String,
    ): List<String> {
        val n = count()
        return List(n.toInt()) { i -> nameOf(i.toULong()) }
    }

    override fun run(
        inputs: Map<String, Tensor>,
        outputs: Set<String>,
        runOptions: RunOptions?,
    ): Map<String, Tensor> = memScoped {
        require(inputs.isNotEmpty()) { "At least one input is required" }

        val inputNameList = inputs.keys.toList()
        val ortInputNames = allocArray<CPointerVar<ByteVar>>(inputNameList.size)
        for (i in inputNameList.indices) ortInputNames[i] = inputNameList[i].cstr.getPointer(memScope)

        val ortInputValues = allocArray<CPointerVar<OrtValue>>(inputNameList.size)
        val inputValues = mutableListOf<CPointer<OrtValue>?>()
        try {
            for (i in inputNameList.indices) {
                val value = inputs.getValue(inputNameList[i]).toOrtValue(this)
                ortInputValues[i] = value
                inputValues += value
            }

            val outputNameList = outputs.toList()
            val ortOutputNames = allocArray<CPointerVar<ByteVar>>(outputNameList.size)
            for (i in outputNameList.indices) ortOutputNames[i] = outputNameList[i].cstr.getPointer(memScope)
            val ortOutputValues = allocArray<CPointerVar<OrtValue>>(outputNameList.size)

            Ort.api.Run!!(
                ptr,
                (runOptions as? NativeRunOptions)?.ptr,
                ortInputNames,
                ortInputValues,
                inputNameList.size.toULong(),
                ortOutputNames,
                outputNameList.size.toULong(),
                ortOutputValues,
            ).check()

            val result = LinkedHashMap<String, Tensor>(outputNameList.size)
            try {
                for (i in outputNameList.indices) {
                    val outPtr = ortOutputValues[i]
                        ?: throw OnnxRuntimeException(-1, "Session returned null output '${outputNameList[i]}'")
                    result[outputNameList[i]] = outPtr.toTensor()
                }
            } finally {
                for (i in outputNameList.indices) {
                    ortOutputValues[i]?.let { Ort.api.ReleaseValue!!(it) }
                }
            }
            result
        } finally {
            inputValues.forEach { if (it != null) Ort.api.ReleaseValue!!(it) }
        }
    }

    override fun close() {
        if (!closed) {
            closed = true
            if (ptr != null) Ort.api.ReleaseSession!!(ptr)
        }
    }
}

internal fun readFileBytes(path: String): ByteArray {
    val file = fopen(path, "rb") ?: throw OnnxRuntimeException(-1, "Failed to open model file: $path")
    try {
        fseek(file, 0, SEEK_END)
        val size = ftell(file)
        fseek(file, 0, SEEK_SET)
        if (size <= 0) return ByteArray(0)
        val buffer = ByteArray(size.toInt())
        val read = buffer.usePinned { pinned ->
            fread(pinned.addressOf(0), 1u, size.toULong(), file)
        }
        if (read != size.toULong()) {
            throw OnnxRuntimeException(-1, "Failed to read model file: $path")
        }
        return buffer
    } finally {
        fclose(file)
    }
}

actual fun createEnv(logLevel: LogLevel, logId: String): Env = memScoped {
    val out = alloc<CPointerVar<OrtEnv>>()
    Ort.api.CreateEnv!!(logLevel.toOrt(), logId.cstr.getPointer(memScope), out.ptr).check()
    NativeEnv(out.value)
}

actual fun createSessionOptions(): SessionOptions = memScoped {
    val out = alloc<CPointerVar<OrtSessionOptions>>()
    Ort.api.CreateSessionOptions!!(out.ptr).check()
    NativeSessionOptions(out.value)
}

actual fun createRunOptions(): RunOptions = memScoped {
    val out = alloc<CPointerVar<OrtRunOptions>>()
    Ort.api.CreateRunOptions!!(out.ptr).check()
    NativeRunOptions(out.value)
}

actual fun createSession(env: Env, modelPath: String, options: SessionOptions?): Session =
    createSession(env, readFileBytes(modelPath), options)

actual fun createSession(env: Env, model: ByteArray, options: SessionOptions?): Session {
    val nativeEnv = env as NativeEnv
    return model.usePinned { pinned ->
        memScoped {
            val out = alloc<CPointerVar<OrtSession>>()
            Ort.api.CreateSessionFromArray!!(
                nativeEnv.ptr,
                pinned.addressOf(0),
                model.size.toULong(),
                (options as? NativeSessionOptions)?.ptr,
                out.ptr,
            ).check()
            NativeSession(out.value)
        }
    }
}
