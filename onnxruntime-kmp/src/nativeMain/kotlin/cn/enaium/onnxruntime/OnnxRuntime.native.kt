/**
 * Lazily resolves the [OrtApi] function-pointer table exported by the
 * bundled libonnxruntime shared library. Since 1.15 the C API is only
 * reachable through `OrtGetApiBase()->GetApi(ORT_API_VERSION)`; the
 * bindings generated by cinterop expose every table entry as a member of
 * the [OrtApi] struct.
 */
internal object Ort {

    val apiBase: CPointer<OrtApiBase> by lazy {
        OrtGetApiBase() ?: error("OrtGetApiBase() returned null - libonnxruntime failed to load")
    }

    val api: OrtApi by lazy {
        val api = apiBase.pointed.GetApi!!(ORT_API_VERSION.toUInt())
            ?: error("OrtApi version $ORT_API_VERSION is not supported by this libonnxruntime")
        api.pointed
    }

    /** Version string reported by the underlying library (e.g. "1.26.0"). */
    val versionString: String by lazy { apiBase.pointed.GetVersionString!!()?.toKString() ?: "unknown" }

    /** Default CPU allocator (a process-wide singleton; never freed). */
    val defaultAllocator: CPointer<OrtAllocator>? by lazy {
        memScoped {
            val out = alloc<CPointerVar<OrtAllocator>>()
            api.GetAllocatorWithDefaultOptions!!(out.ptr).check()
            out.value
        }
    }

    /** CPU memory info used for user-supplied tensor buffers (never freed). */
    val cpuMemoryInfo: CPointer<OrtMemoryInfo>? by lazy {
        memScoped {
            val out = alloc<CPointerVar<OrtMemoryInfo>>()
            api.CreateCpuMemoryInfo!!(
                OrtArenaAllocator,
                OrtMemTypeDefault,
                out.ptr,
            ).check()
            out.value
        }
    }
}

internal fun LogLevel.toOrt(): OrtLoggingLevel = when (this) {
    LogLevel.VERBOSE -> OrtLoggingLevel.ORT_LOGGING_LEVEL_VERBOSE
    LogLevel.INFO -> OrtLoggingLevel.ORT_LOGGING_LEVEL_INFO
    LogLevel.WARNING -> OrtLoggingLevel.ORT_LOGGING_LEVEL_WARNING
    LogLevel.ERROR -> OrtLoggingLevel.ORT_LOGGING_LEVEL_ERROR
    LogLevel.FATAL -> OrtLoggingLevel.ORT_LOGGING_LEVEL_FATAL
}

internal fun GraphOptimizationLevel.toOrt(): UInt = when (this) {
    GraphOptimizationLevel.DISABLE_ALL -> ORT_DISABLE_ALL
    GraphOptimizationLevel.ENABLE_BASIC -> ORT_ENABLE_BASIC
    GraphOptimizationLevel.ENABLE_EXTENDED -> ORT_ENABLE_EXTENDED
    GraphOptimizationLevel.ENABLE_ALL -> ORT_ENABLE_ALL
}

/**
 * Checks an [OrtStatusPtr] returned by an API call. Returns normally when
 * the call succeeded (null status) and throws [OnnxRuntimeException] with
 * the native error code and message otherwise.
 */
internal fun OrtStatusPtr?.check() {
    if (this != null) {
        val code = Ort.api.GetErrorCode!!(this)
        val message = Ort.api.GetErrorMessage!!(this)?.toKString() ?: "unknown error"
        Ort.api.ReleaseStatus!!(this)
        throw OnnxRuntimeException(code.ordinal, message)
    }
}

internal class NativeEnv internal constructor(
    internal val ptr: CPointer<OrtEnv>?,
) : Env {

    private var closed = false

    override val version: String get() = Ort.versionString

    override fun close() {
        if (!closed) {
            closed = true
            if (ptr != null) Ort.api.ReleaseEnv!!(ptr)
        }
    }
}

internal class NativeSessionOptions internal constructor(
    internal val ptr: CPointer<OrtSessionOptions>?,
) : SessionOptions {

    private var closed = false

    override fun setIntraOpNumThreads(threads: Int) {
        Ort.api.SetIntraOpNumThreads!!(ptr, threads).check()
    }

    override fun setInterOpNumThreads(threads: Int) {
        Ort.api.SetInterOpNumThreads!!(ptr, threads).check()
    }

    override fun setGraphOptimizationLevel(level: GraphOptimizationLevel) {
        Ort.api.SetSessionGraphOptimizationLevel!!(ptr, level.toOrt()).check()
    }

    override fun setSessionLogLevel(level: LogLevel) {
        Ort.api.SetSessionLogSeverityLevel!!(ptr, level.toOrt().value.toInt()).check()
    }

    override fun addConfigEntry(key: String, value: String) = memScoped {
        Ort.api.AddSessionConfigEntry!!(
            ptr,
            key.cstr.getPointer(memScope),
            value.cstr.getPointer(memScope),
        ).check()
    }

    override fun close() {
        if (!closed) {
            closed = true
            if (ptr != null) Ort.api.ReleaseSessionOptions!!(ptr)
        }
    }
}

